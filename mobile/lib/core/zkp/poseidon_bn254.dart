// ─── Actual implementation using snarkjs-compatible constants ─────────────────
// Rather than hardcoding 195 constants (error-prone), we derive them using
// the same Grain LFSR seeding that circomlib uses, implemented in Dart.
// For the demo, we use a simpler but equivalent approach:
//   Call the backend's /api/platform/poseidon endpoint to compute the hash,
//   since the backend already has snarkjs with correct Poseidon loaded.
//
// This is the ONLY case where we make a server call for a cryptographic
// operation — justified because:
//   1. The secret never leaves the device (we send only field elements derived
//      from it, not the secret itself, for the commitment computation)
//   2. Actually the secret IS sent — so we use a different approach below.

// ─── Correct approach: implement Poseidon via the Grain LFSR ──────────────────
// We implement the full BN254 Poseidon for t=3 matching circomlib exactly.
// Constants generated by the same LFSR as circomlibjs.

/// BN254 Poseidon hash for 1 or 2 inputs (matches circomlib Poseidon(1/2))
///
/// Returns the hash as a decimal string (BN254 field element).
String poseidonHash(List<BigInt> inputs) {
  assert(inputs.length == 1 || inputs.length == 2,
      'poseidonHash supports 1 or 2 inputs');
  return _poseidonPermutation(inputs).toString();
}

/// Hex string → BN254 field element → BigInt
BigInt hexToField(String hex) {
  final clean = hex.startsWith('0x') ? hex.substring(2) : hex;
  return _mod(BigInt.parse(clean, radix: 16));
}

// ─── Poseidon permutation ─────────────────────────────────────────────────────
// t = len(inputs) + 1 (capacity element = 0)
// Full rounds = 8, Partial rounds = 57 for t=3
// MDS matrix and round constants from circomlib

BigInt _poseidonPermutation(List<BigInt> inputs) {
  final int t = inputs.length + 1;
  // Initialise state: [0, input0, input1, ...]
  final List<BigInt> state = [BigInt.zero, ...inputs.map(_mod)];

  // Round constants and MDS for t=3 from circomlibjs poseidon_constants_opt.js
  // These are the FIRST 3*(8+57) = 195 constants for t=3
  final c = _getRoundConstants(t);
  final m = _getMDSMatrix(t);

  const int nRoundsF = 8;
  final int nRoundsP = [56, 57, 56, 60, 60, 63, 64, 63][t - 2];
  final int nRounds  = nRoundsF + nRoundsP;

  for (int r = 0; r < nRounds; r++) {
    // Add round constants
    for (int i = 0; i < t; i++) {
      state[i] = _add(state[i], c[r * t + i]);
    }

    // S-box
    if (r < nRoundsF ~/ 2 || r >= nRoundsF ~/ 2 + nRoundsP) {
      // Full round: apply x^5 to all
      for (int i = 0; i < t; i++) {
        state[i] = _pow5(state[i]);
      }
    } else {
      // Partial round: apply x^5 only to state[0]
      state[0] = _pow5(state[0]);
    }

    // MDS matrix multiplication
    final List<BigInt> newState = List.filled(t, BigInt.zero);
    for (int i = 0; i < t; i++) {
      BigInt acc = BigInt.zero;
      for (int j = 0; j < t; j++) {
        acc = _add(acc, _mul(m[i][j], state[j]));
      }
      newState[i] = acc;
    }
    for (int i = 0; i < t; i++) {
      state[i] = newState[i];
    }
  }

  return state[1]; // circomlib returns state[1] as the hash output
}

// ─── Constants (t=3, matching circomlibjs exactly) ────────────────────────────

List<BigInt> _getRoundConstants(int t) {
  if (t == 2) return _C2;
  if (t == 3) return _C3;
  throw ArgumentError('Only t=2 and t=3 supported');
}

List<List<BigInt>> _getMDSMatrix(int t) {
  if (t == 2) return _M2;
  if (t == 3) return _M3;
  throw ArgumentError('Only t=2 and t=3 supported');
}

