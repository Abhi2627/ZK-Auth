/// Poseidon hash for BN254 — matches circomlib Poseidon(1) and Poseidon(2)
///
/// Used to compute:
///   commitment = Poseidon([secret])        — sent at registration
///   nullifier  = Poseidon([secret, nonce]) — sent as publicSignals[0]
///
/// These must exactly match what auth.circom computes inside the WASM prover.
///
/// Implementation:
///   BN254 scalar field, t=3 (2 inputs), Poseidon permutation.
///   Round constants and MDS matrix from circomlibjs poseidon_constants_opt.js.
///   8 full rounds + 57 partial rounds (nRoundsF=8, nRoundsP=57 for t=3).

library poseidon_bn254;

// ─── BN254 field arithmetic ───────────────────────────────────────────────────

final BigInt _p = BigInt.parse(
  '21888242871839275222246405745257275088548364400416034343698204186575808495617',
);

BigInt _mod(BigInt a) => ((a % _p) + _p) % _p;
BigInt _add(BigInt a, BigInt b) => _mod(a + b);
BigInt _mul(BigInt a, BigInt b) => _mod(a * b);

BigInt _pow5(BigInt x) {
  final x2 = _mul(x, x);
  final x4 = _mul(x2, x2);
  return _mul(x4, x);
}

